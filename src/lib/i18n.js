const I18nContext = createContext({
  lang: 'en',
  setLang: () => {},
  isAuto: true,
  setIsAuto: () => {},
  t: (k) => k,
  supportedLanguages: SUPPORTED_LANGUAGES,
});

export function I18nProvider({ children }) {
  const [isAuto, setIsAutoState] = useState(() => {
    return localStorage.getItem('rsstg_lang_auto') !== 'false';
  });

  const [currentLang, setCurrentLangState] = useState(() => {
    const savedAuto = localStorage.getItem('rsstg_lang_auto') !== 'false';
    if (!savedAuto) {
      const savedLang = localStorage.getItem('rsstg_lang');
      if (savedLang) return normalizeLanguageCode(savedLang);
    }
    const tgUser = getTelegramUser();
    const detected = tgUser?.language_code || (typeof navigator !== 'undefined' ? navigator.language : 'en');
    return normalizeLanguageCode(detected);
  });

  const setLanguage = (newLangCode, auto = false) => {
    setIsAutoState(auto);
    localStorage.setItem('rsstg_lang_auto', auto ? 'true' : 'false');

    if (auto) {
      const tgUser = getTelegramUser();
      const detected = tgUser?.language_code || (typeof navigator !== 'undefined' ? navigator.language : 'en');
      const normalized = normalizeLanguageCode(detected);
      setCurrentLangState(normalized);
      localStorage.removeItem('rsstg_lang');
    } else {
      const normalized = normalizeLanguageCode(newLangCode);
      setCurrentLangState(normalized);
      localStorage.setItem('rsstg_lang', normalized);
    }
  };

  const t = (key, params = {}) => {
    const dict = UI_TRANSLATIONS[currentLang] || UI_TRANSLATIONS.en;
    let text = dict[key] || UI_TRANSLATIONS.en[key] || key;

    for (const [k, v] of Object.entries(params)) {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    }
    return text;
  };

  return React.createElement(
    I18nContext.Provider,
    {
      value: {
        lang: currentLang,
        setLang: (l) => setLanguage(l, false),
        setAutoLang: () => setLanguage('en', true),
        isAuto,
        t,
        supportedLanguages: SUPPORTED_LANGUAGES,
      },
    },
    children
  );
}

export function useI18n() {
  return useContext(I18nContext);
}
